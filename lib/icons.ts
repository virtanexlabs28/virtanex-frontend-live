import {
  Activity,
  Bot,
  Boxes,
  Briefcase,
  Building2,
  CheckCircle2,
  Cloud,
  Code2,
  Cpu,
  Database,
  Factory,
  GitMerge,
  Globe2,
  HeartPulse,
  Landmark,
  Laptop,
  Layers,
  Palette,
  Radio,
  SearchCheck,
  ShieldCheck,
  ShoppingBag,
  Workflow,
  Zap,
  type LucideIcon,
} from 'lucide-react';

const ICONS: Record<string, LucideIcon> = {
  Activity,
  Bot,
  Boxes,
  Briefcase,
  Building2,
  CheckCircle2,
  Cloud,
  Code2,
  Cpu,
  Database,
  Factory,
  GitMerge,
  Globe2,
  HeartPulse,
  Landmark,
  Laptop,
  Layers,
  Palette,
  Radio,
  SearchCheck,
  ShieldCheck,
  ShoppingBag,
  Workflow,
  Zap,
};

/** Resolve an icon name stored in a JSON data file to its Lucide component. */
export function getIcon(name: string): LucideIcon {
  return ICONS[name] ?? Code2;
}
